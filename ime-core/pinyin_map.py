def get_char_tuples(
    syllable: str,
    max_count: int = 15,
    expand_initials: bool = True,
    user_weights: dict[str, dict[str, float]] = None,
) -> list[tuple[str, float]]:
    """Get weighted (char, score) tuples, expanding initials if enabled."""
    if expand_initials and len(syllable) == 1 and syllable in INITIAL_MAP:
        expanded_syls = INITIAL_MAP[syllable]
        if not expanded_syls:
            return []
        merged: dict[str, float] = {}
        for fs in expanded_syls:
            entries = get_weighted_char_tuples(fs, max_count=max_count,
                                               user_weights=user_weights)
            for ch, sc in entries:
                if ch not in merged or sc > merged[ch]:
                    merged[ch] = sc
        sorted_chars = sorted(merged.items(), key=lambda x: -x[1])
        return sorted_chars[:max_count]
    return get_weighted_char_tuples(syllable, max_count=max_count,
                                    user_weights=user_weights)


def get_characters(syllable: str, max_count: int = 10) -> list[str]:
    """Return top N characters for a pinyin syllable."""
    return SYLLABLE_MAP.get(syllable.lower(), [])[:max_count]


def get_weighted_characters(
    syllable: str,
    max_count: int = 10,
) -> list[str]:
    """Return top N characters for a pinyin syllable, frequency-ordered."""
    return get_characters(syllable, max_count=max_count)


def get_weighted_char_tuples(
    syllable: str,
    max_count: int = 15,
    user_weights: dict[str, dict[str, float]] = None,
) -> list[tuple[str, float]]:
    """Return (char, freq_score) tuples, sorted by score descending.

    If user_weights are provided, boosts characters the user frequently
    selects for this syllable (up to +0.5 over base score).
    """
    chars = SYLLABLE_MAP.get(syllable.lower(), [])[:max_count]
    if not chars:
        return []
    n = len(chars)
    pairs = [(ch, max(0.1, 1.0 - i * 0.9 / n)) for i, ch in enumerate(chars)]

    # Apply user preference boost
    if user_weights and syllable in user_weights:
        uweights = user_weights[syllable]
        total = sum(uweights.values()) or 1
        for i, (ch, base) in enumerate(pairs):
            boost = uweights.get(ch, 0) / total * 0.5  # max +0.5 boost
            pairs[i] = (ch, base + boost)
        pairs.sort(key=lambda x: -x[1])

    return pairs


def segment_pinyin(pinyin: str) -> list[str]:
    """
    Greedy segmentation of pinyin into syllables, with 简拼 support.

    Handles:
      - Space-separated pinyin  "ni hao"
      - Continuous pinyin       "womenyinggaizenmeban"
      - Abbreviation initials   "nh"  → "n" + "h"
      - Mixed                   "wmen" → "w" + "men"
    """
    if not pinyin:
        return []

    # If there are spaces, split by spaces first
    if " " in pinyin.strip():
        parts = pinyin.strip().split()
        result = []
        for part in parts:
            if not part:
                continue
            result.extend(segment_pinyin(part))
        return result

    # Greedy longest-match segmentation
    pinyin = pinyin.strip().lower()
    syllables = []
    i = 0
    max_len = 6  # longest valid pinyin syllable

    while i < len(pinyin):
        matched = False
        # Try longest match first
        for end in range(min(i + max_len, len(pinyin)), i, -1):
            cand = pinyin[i:end]
            if cand in SYLLABLE_MAP:
                syllables.append(cand)
                i = end
                matched = True
                break
        if not matched:
            # If single character is a valid initial, keep it for expansion
            if pinyin[i] in INITIAL_MAP:
                syllables.append(pinyin[i])
            else:
                # Genuine unknown character — still include it
                syllables.append(pinyin[i])
            i += 1

    return syllables


def segment_pinyin_all(pinyin: str) -> list[tuple[list[str], float]]:
    """Generate all valid pinyin segmentations with path confidence scores.

    Handles ambiguity like 'xian' → ['xian'] or ['xi', 'an'].
    Each path scored by syllable validity and frequency.

    Returns: [(syllables, score), ...] sorted by score descending.
    """
    if not pinyin:
        return []

    if " " in pinyin.strip():
        parts = pinyin.strip().split()
        # Recurse for each space-separated part, then combine all paths
        paths = [segment_pinyin_all(p) for p in parts]
        if not paths:
            return []
        # Cartesian product of paths across parts
        from itertools import product as iter_product
        result = []
        for combo in iter_product(*paths):
            all_syl = []
            total_score = 1.0
            for syl_list, score in combo:
                all_syl.extend(syl_list)
                total_score *= score
            result.append((all_syl, total_score))
        result.sort(key=lambda x: -x[1])
        return result

    pinyin = pinyin.strip().lower()
    n = len(pinyin)
    if n == 0:
        return []

    max_len = 6
    from collections import defaultdict

    # DP: pos -> [(syllables, score, last_syllable)]
    dp: dict[int, list[tuple[list[str], float, str]]] = defaultdict(list)
    dp[0] = [([], 1.0, "")]

    for i in range(n):
        if i not in dp:
            continue
        for end in range(i + 1, min(i + max_len, n) + 1):
            cand = pinyin[i:end]
            if cand in SYLLABLE_MAP:
                total_chars = len(SYLLABLE_MAP[cand])
                # Frequency score: penalize rare syllables aggressively
                # Common (30+ chars): ~0.94, Rare (1 char): ~0.33
                freq_score = min(0.98, total_chars / (total_chars + 2))
                for syllables, score, last in dp[i]:
                    split_penalty = 0.97 if last and last != cand else 1.0
                    new_score = score * freq_score * split_penalty
                    dp[end].append((syllables + [cand], new_score, cand))

        # Also try single-character initial expansion (简拼)
        if i < n and pinyin[i] in INITIAL_MAP:
            expanded = INITIAL_MAP[pinyin[i]]
            if expanded:
                # For each expanded full syllable
                for fs in expanded[:3]:  # limit to top 3 expansions
                    if fs in SYLLABLE_MAP:
                        freq_score = 0.5  # lower confidence for 简拼
                        for syllables, score, last in dp[i]:
                            new_score = score * freq_score
                            dp[i + 1].append(
                                (syllables + [pinyin[i]], new_score, fs)
                            )

    if n not in dp:
        # Fallback: use greedy segmentation
        return [(segment_pinyin(pinyin), 0.1)]

    # Deduplicate and sort paths
    seen = set()
    result = []
    for syllables, score, _ in sorted(dp[n], key=lambda x: -x[1]):
        key = " ".join(syllables)
        if key not in seen:
            seen.add(key)
            result.append((syllables, round(score, 4)))

    return result[:5]  # top 5 paths max


def generate_candidates(
    pinyin_input: str,
    max_combinations: int = 36,
    user_weights: dict[str, dict[str, float]] = None,
    phrase_boost: dict[str, str] = None,
) -> list[str]:
    """Generate candidate word sequences from pinyin input.

    Strategy (for multi-syllable):
      1. Look up WORD_MAP for exact pinyin → include those words first.
      2. If user has a preferred phrase (phrase_boost), move it to front.
      3. Fall back to character-level cartesian combinations.
      4. Deduplicate while preserving order.

    Args:
        user_weights: {syllable: {char: boost_ratio}} — boosts user-preferred chars
        phrase_boost: {pinyin_key: preferred_phrase} — promotes user's top phrase
    """
    syllables = segment_pinyin(pinyin_input.strip())
    if not syllables:
        return []

    # Single syllable: return weighted characters (expand initials)
    if len(syllables) == 1:
        tups = get_char_tuples(syllables[0], max_count=max_combinations,
                                user_weights=user_weights)
        return [ch for ch, _ in tups]

    candidates: list[str] = []
    seen: set[str] = set()
    pinyin_key = " ".join(syllables)

    # Step 1: WORD_MAP lookup (exact multi-syllable words)
    word_candidates = WORD_MAP.get(pinyin_key, [])
    # If user has a top phrase for this key, promote it to front
    if phrase_boost and pinyin_key in phrase_boost:
        top = phrase_boost[pinyin_key]
        if top in word_candidates:
            reordered = [top] + [w for w in word_candidates if w != top]
            word_candidates = reordered
        else:
            word_candidates = [top] + word_candidates
    for w in word_candidates:
        if w not in seen:
            candidates.append(w)
            seen.add(w)

    remaining = max_combinations - len(candidates)
    if remaining <= 0:
        return candidates[:max_combinations]

    # Step 2: Cartesian combinations as fallback
    base_max = 10
    first_tups = get_char_tuples(syllables[0], max_count=base_max,
                                  user_weights=user_weights)
    first_chars = [ch for ch, _ in first_tups]
    for ch in first_chars:
        if len(candidates) >= max_combinations:
            break
        rest = generate_candidates(" ".join(syllables[1:]),
                                   max_combinations - len(candidates),
                                   user_weights=user_weights,
                                   phrase_boost=phrase_boost)
        if not rest:
            if ch not in seen:
                candidates.append(ch)
                seen.add(ch)
        else:
            for rc in rest:
                combo = ch + rc
                if combo not in seen:
                    candidates.append(combo)
                    seen.add(combo)
                    if len(candidates) >= max_combinations:
                        break

    return candidates[:max_combinations]


def syllable_count(pinyin_input: str) -> int:
    """Count how many syllables are in the input."""
    return len(segment_pinyin(pinyin_input.strip()))
