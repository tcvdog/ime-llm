def extract_bigrams(text: str) -> list[str]:
    """Extract all adjacent character pairs from text."""
    bigrams = []
    for i in range(len(text) - 1):
        bigrams.append(text[i:i+2])
    return bigrams


def gen_bigram_table(words: list[str]) -> dict[str, int]:
    """Build bigram→count dict from a list of words."""
    bg_counts: dict[str, int] = {}
    for word in words:
        for bg in extract_bigrams(word):
            bg_counts[bg] = bg_counts.get(bg, 0) + 1
    return bg_counts


def gen_char_unigrams(words: list[str]) -> dict[str, int]:
    """Build character→count from the word list."""
    counts: dict[str, int] = {}
    for word in words:
        for ch in word:
            counts[ch] = counts.get(ch, 0) + 1
    return counts


